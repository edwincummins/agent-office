// Full client/server smoke in throwaway data. Supply a local map and Chromium path.
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { mkdtemp,mkdir,writeFile,readFile,copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const mapFile=process.env.TRAVEL_MAP,out=process.env.TRAVEL_PROOF_DIR,port=Number(process.env.TRAVEL_PROOF_PORT||4678);
if(!mapFile||!out||[4600,4632,4660].includes(port))throw Error('Supply map, proof directory and an isolated port');
const root=await mkdtemp(path.join(tmpdir(),'travel-app-'));
await writeFile(path.join(root,'.owner-test-only'),'Travel-only synthetic preview');
const maps=path.join(root,'.agent-office','maps');await mkdir(path.join(maps,'assets'),{recursive:true});
const config=JSON.parse(await readFile(mapFile,'utf8'));
await copyFile(mapFile,path.join(maps,'travel-map.json'));
await copyFile(path.join(path.dirname(mapFile),config.model.asset),path.join(maps,'assets',config.model.asset));
await writeFile(path.join(root,'.agent-office','map.json'),JSON.stringify({pick:config.id,by:'Travel QA',at:Date.now()}));
await mkdir(out,{recursive:true});
const server=spawn(process.execPath,['--import','tsx','tests/fixtures/owner-preview.ts',root,String(port)],{windowsHide:true,stdio:['ignore','pipe','pipe']});
let log='';server.stdout.on('data',b=>log+=b);server.stderr.on('data',b=>log+=b);
const stop=()=>new Promise(resolve=>{const kill=spawn('taskkill',['/pid',String(server.pid),'/T','/F'],{windowsHide:true,stdio:'ignore'});kill.on('exit',resolve);});
const timer=setTimeout(()=>{void stop();process.exitCode=124;},90000);
let browser;
try{
 const base='http://127.0.0.1:'+port;
 for(let i=0;i<100;i++){try{if((await fetch(base+'/api/onboarding')).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
 browser=await chromium.launch({headless:true,executablePath:process.env.TRAVEL_CHROME,args:['--use-angle=d3d11','--enable-gpu','--ignore-gpu-blocklist']});
 const context=await browser.newContext({viewport:{width:1280,height:800}});
 const login=await context.request.post(base+'/api/login',{headers:{Origin:base},data:{name:'Test Owner',password:'synthetic-password-only'}});
 assert.equal(login.status(),200);
 await context.addInitScript(()=>localStorage.setItem('agent-office.profile',JSON.stringify({name:'Test Owner',color:'#4f86f7',look:{}})));
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')console.error(m.text().slice(0,500));});
 await page.goto(base);
 await page.waitForFunction(id=>window.__office?.plan().id===id&&window.__office.store.floor&&window.__office.world().group.children.length>0,config.id,{timeout:30000});
 console.log('Initial dialogs',await page.locator('.modal h2').allTextContents());
 for(let i=0;i<4&&await page.locator('.backdrop').count();i++)await page.keyboard.press('Escape');
 await page.waitForFunction(()=>{let loaded=false;window.__office.world().group.traverse(o=>{const ms=Array.isArray(o.material)?o.material:[o.material];if(ms.some(m=>m?.userData.localModel))loaded=true;});return loaded;},null,{timeout:20000});
 await page.waitForFunction(()=>window.__office.renderer.info.render.calls>0,null,{timeout:10000});
 await page.keyboard.press('j');await page.getByRole('dialog',{name:'Go to',exact:true}).waitFor();
 await page.screenshot({animations:'disabled',path:out+'/app-travel-desktop.png'});
 await page.locator('[data-place=home]').click();
 await page.waitForFunction(at=>Math.abs(window.__office.player.pos.y-at.y)<.15&&Math.hypot(window.__office.player.pos.x-at.x,window.__office.player.pos.z-at.z)<=1.51,config.travel.home);
 const home=await page.evaluate(()=>{const r=window.__office.renderer,gl=r.getContext(),debug=gl.getExtension('WEBGL_debug_renderer_info');return {position:window.__office.player.pos.toArray(),seat:window.__office.player.seat,enabled:window.__office.player.enabled,calls:r.info.render.calls,gpu:debug?gl.getParameter(debug.UNMASKED_RENDERER_WEBGL):'unavailable'};});
 assert.equal(home.seat,null);assert.equal(home.enabled,true);
 await page.screenshot({animations:'disabled',path:out+'/app-home.png'});
 await page.keyboard.press('j');await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.pointerLockElement!==null,{timeout:3000});
 await page.keyboard.press('j');await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.waitForFunction(()=>document.pointerLockElement!==null,{timeout:3000});
 const destination=config.travel.places.find(p=>p.at.y>0)??config.travel.places[0];
 await page.keyboard.press('j');await page.locator('[data-place="'+destination.id+'"]').click();
 await page.waitForFunction(at=>Math.abs(window.__office.player.pos.y-at.y)<.15&&Math.hypot(window.__office.player.pos.x-at.x,window.__office.player.pos.z-at.z)<=1.51,destination.at);
 await page.setViewportSize({width:390,height:844});await page.keyboard.press('j');
 await page.screenshot({animations:'disabled',path:out+'/app-travel-mobile.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=390),true);
 assert.deepEqual(errors,[]);
 await writeFile(path.join(out,'app-proof.json'),JSON.stringify({home,destination,errors,root,port},null,2));
 console.log('Actual app travel proof passed',JSON.stringify(home));
}catch(e){console.error(log.slice(-4000));throw e;}finally{clearTimeout(timer);await browser?.close();await stop();}
